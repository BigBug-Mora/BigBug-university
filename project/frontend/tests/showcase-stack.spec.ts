import { expect, test } from "@playwright/test";

test.use({ actionTimeout: 15000 });

test("seller authors, previews and publishes the no-photo showcase through the UI", async ({ page }, testInfo) => {
  test.setTimeout(90000);
  await page.goto("/seller/workspace");
  await page.getByRole("button", { name: "Sign in with Cognito" }).click();
  await page.getByRole("link", { name: "Approve as seller" }).click();
  await expect(page.getByRole("heading", { name: "Seller workspace" })).toBeVisible();
  await page.getByRole("button", { name: "Create draft" }).click();
  await expect(page.getByRole("heading", { name: "house draft", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Apply authored starter" }).click();
  await page.getByRole("button", { name: "Save showcase", exact: true }).click();
  await expect(page.getByText("Showcase saved.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Publish listing", exact: true }).click();
  await expect(page.getByText(/Publication requires:/)).toBeVisible();
  await page.getByLabel("District", { exact: true }).fill("Fictional District");
  await page.getByLabel("Town", { exact: true }).fill("Courtyard Town");
  await page.getByLabel("Price basis").selectOption("total");
  await page.getByLabel("Entered price").fill("100000");
  await page.getByLabel("Currency", { exact: true }).fill("LKR");
  await page.getByLabel("Land area", { exact: true }).fill("12");
  await page.getByRole("combobox", { name: "Land area unit", exact: true }).selectOption("perch");
  await page.getByLabel("Bedroom count", { exact: true }).fill("0");
  await page.getByLabel("Bathroom count", { exact: true }).fill("1");
  await page.getByLabel("Parking spaces", { exact: true }).fill("0");
  await page.getByRole("combobox", { name: "Vehicle access", exact: true }).selectOption("false");
  await page.getByLabel("Access road width", { exact: true }).fill("15");
  await page.getByRole("combobox", { name: "Road unit", exact: true }).selectOption("ft");
  await page.getByLabel("Show access road width on the published page").check();
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByText("Draft saved.", { exact: true })).toBeVisible();
  await expect(page.getByText(/showcase is based on an earlier revision/)).toBeVisible();
  await page.getByLabel("Phone 1", { exact: true }).fill("+15550101111");
  await page.getByRole("button", { name: "Save phone 1", exact: true }).click();
  await expect(page.getByRole("button", { name: "Remove phone 1", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Apply authored starter" }).click();
  await page.getByRole("button", { name: "Save showcase", exact: true }).click();
  await expect(page.getByText("Ready to publish this revision and showcase.")).toBeVisible();
  await page.getByRole("link", { name: "Preview showcase" }).click();
  await expect(page.getByText("Seller preview · Not a publication")).toBeVisible();
  await expect(page.getByRole("heading", { name: "House in Courtyard Town, Fictional District" })).toBeVisible();
  await expect(page.getByText("No photos published yet")).toBeVisible();
  await expect(page.locator("article img")).toHaveCount(0);
  await expect(page.getByTestId("asking-price")).toHaveText("LKR 100,000");
  await expect(page.locator(".showcase-fact-row").filter({ hasText: "Vehicle access" })).toContainText("No");
  await expect(page.locator(".showcase-fact-row").filter({ hasText: "Parking spaces" }).first()).toContainText("0");
  await expect(page.getByText("15 ft", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Publish listing", exact: true }).click();
  await expect(page.getByText("Listing published.", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "View published listing" }).click();
  await expect(page.getByRole("heading", { name: "House in Courtyard Town, Fictional District" })).toBeVisible();
  await expect(page.getByText("Seller preview · Not a publication")).toHaveCount(0);
  await expect(page.getByTestId("asking-price")).toHaveText("LKR 100,000");
  await expect(page.locator("article img")).toHaveCount(0);
  await expect(page.getByText("+15550101111", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("showcase-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("showcase-mobile.png"), fullPage: true });
});
